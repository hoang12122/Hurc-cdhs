"""Offline retrieval engine used by the HURC1 Copilot fallback.

The module intentionally depends only on Python's standard library so it can run
inside the existing Next.js server action without installing an ML stack. It
implements a small hybrid lexical retriever (BM25 + phrase/category bonuses),
loads versioned ingestion indexes when available, and preserves the historical
JSON response contract consumed by ``askCopilot``.
"""

